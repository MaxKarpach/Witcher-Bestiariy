export function describeLootItem(item: string) {
  const normalized = item.toLowerCase();
  const exactAlchemy = alchemyCatalogNotes[item];
  const exactArmor = armorCatalogNotes[item];

  if (exactAlchemy) return exactAlchemy;
  if (exactArmor) return exactArmor;

  const fuzzyAlchemy = Object.entries(alchemyCatalogNotes).find(([name]) => normalized.includes(name.toLowerCase()));
  if (fuzzyAlchemy) return fuzzyAlchemy[1];

  const fuzzyArmor = Object.entries(armorCatalogNotes).find(([name]) => normalized.includes(name.toLowerCase()));
  if (fuzzyArmor) return fuzzyArmor[1];

  if (/мутаген/i.test(item)) {
    return "Мутаген выдается по решению мастера; тип существа можно использовать как ориентир для отваров и ведьмачьих рецептов.";
  }

  if (/монет|крон|орен|флорен|дукат|бизант|ценност/i.test(item)) {
    return "Сумму лучше назначать по сцене: обычный враг дает мелочь, важный NPC или логово - заметную добычу.";
  }

  if (/пб \d+/i.test(item)) {
    return "Защитное снаряжение по карточке существа. ПБ можно перенести в сцену как трофей или поврежденную броню.";
  }

  if (/нет/i.test(item)) return "";

  return "Нет точной строки в каталогах; оставлено как сценическая добыча, которую мастер может оценить по редкости.";
}
